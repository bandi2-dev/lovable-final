function EnvBadge() {
  if (env.APP_ENV === "prod") return null;
  const colors: Record<string, string> = {
    local: "bg-emerald-500",
    dev: "bg-blue-500",
    test: "bg-amber-500",
  };
  return (
    <div className="fixed bottom-3 left-3 z-50 pointer-events-none">
      <span
        className={`inline-flex items-center gap-1 rounded-full px-2.5 py-1 text-[10px] font-semibold uppercase tracking-wider text-white shadow-lg ${colors[env.APP_ENV] ?? "bg-slate-500"}`}
      >
        <span className="h-1.5 w-1.5 rounded-full bg-white/90" /> {env.APP_ENV}
      </span>
    </div>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <Outlet />
      <EnvBadge />
      <Toaster richColors position="top-center" />
    </QueryClientProvider>
  );
}
